/**
 * 거제 9미 — 거제시가 정한 아홉 가지 향토 음식(tour.geoje.go.kr 「거제 9경9미9품 > 거제 9미」).
 *
 * 9경과 다른 점: 9경은 **장소**라 스팟에 바로 붙지만, 9미는 **음식**이라 가게에 바로 붙지 않습니다.
 * 거제시는 9미로 식당을 지정하지 않습니다 — 아홉 상세 페이지 전부에 식당 목록이 없습니다(2026-09-20 확인).
 * 그래서 어느 맛집이 어느 미인지는 **서버가 줍니다**(`/api/places` 의 `nineTasteNos`, V47 —
 * 거제시 9미 목록과 TourAPI 대표메뉴 · 가게 이름을 대조한 결과). 9경 번호를 서버가 쥐는 것과 같습니다.
 *
 * 스팟 이름을 i18n 사전에 두지 않는 규칙(ko.js 머리말)과 같은 이유로 여기 둡니다 —
 * 화면 문구가 아니라 **거제시가 정한 데이터**입니다. 번호는 거제시 누리집 표시 순서입니다
 * (누리집이 「N미」라고 번호를 붙이지는 않습니다 — 9경과 같이 순서를 번호로 읽습니다).
 *
 * 음식마다의 **제철**(`season`)은 거제시 원문입니다(기준문서 §6 「거제 9미」 — 2026-09-21 몽꾸 시트의 9미 답이 씁니다).
 * 8 · 9미는 **원문에 제철 칸 자체가 없어** null 입니다 — 지어 넣지 않습니다(절대규칙 1). 화면은 그 줄을 비웁니다.
 */
export const NINE_TASTES = [
  { no: 1, name: '거제대구탕', season: '11월~2월' },
  { no: 2, name: '거제굴구이', season: '10월~4월' },
  { no: 3, name: '멍게&성게비빔밥', season: '연중' },
  { no: 4, name: '거제도다리쑥국', season: '3월~5월' },
  { no: 5, name: '거제물메기탕', season: '11월~3월' },
  { no: 6, name: '거제멸치쌈밥&회무침', season: '연중' },
  { no: 7, name: '거제생선회&물회', season: '연중' },
  { no: 8, name: '코끼리&왕우럭조개 숙회', season: null },
  { no: 9, name: '맹종죽순 요리', season: null },
]

/** 이 곳이 내는 9미의 이름들(거제시 원문). 9미가 아니면 빈 배열입니다. */
export function tasteNamesOf(place) {
  return (place?.nineTasteNos ?? [])
    .map((no) => NINE_TASTES.find((taste) => taste.no === no)?.name)
    .filter(Boolean)
}
