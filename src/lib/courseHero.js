/**
 * 코스 추천 카드 사진 — 위 카드에서 이미 쓴 사진이면 그 코스의 다음 스팟 사진을 씁니다(2026-09-17 사용자 결정).
 *
 * 왜: 카드 사진이 첫 스팟 사진이라, 대표 코스 중 둘이 학동몽돌해변 · 둘이 바람의언덕으로 시작하면 **같은 사진이 두 번** 나왔습니다.
 * 코스마다 성격이 다르다는 걸 보여주려는 화면인데 카드가 똑같아 보였습니다(코스재설계 §0).
 *
 * 규칙 — 넘겨받은 목록 순서대로 정합니다:
 *  · 코스의 스팟을 방문 순서대로 보며 **아직 안 쓴 사진이 있는 첫 스팟**. 사진이 없는 스팟(저작권 Type3 · 목록 실패)은 건너뜁니다.
 *  · 전부 이미 쓰였으면 **사진이 있는 첫 스팟**(첫 스팟에 사진이 있으면 곧 첫 스팟 사진 — 이전 동작). 겹쳐도 사진은 보입니다.
 *    첫 스팟에 사진이 없다고 「사진 없음 — TourAPI 사진 0장」으로 떨어지면 사진이 있는 코스에 거짓말을 하게 됩니다.
 *  · 어느 스팟에도 사진이 없으면 null(「사진 없음」).
 *  · 같은 사진은 주소(thumbnailUrl)로 가릅니다.
 *
 * **보이는 카드 목록**을 넘깁니다 — 개수 칩으로 거른 목록이면 거른 목록 기준으로 다시 정해야 가려진 카드가 사진을 선점하지 않습니다.
 * 순수 함수라 같은 목록이면 늘 같은 결과입니다. 링크가 죽은 사진(onError)은 여기서 모릅니다 — 카드가 따로 「사진 없음」으로 떨어집니다.
 *
 * @returns {(string|null)[]} 넘긴 코스와 같은 순서 · 같은 길이
 */
export function heroPhotos(courses) {
  const used = new Set()
  return courses.map((course) => {
    const urls = (course.spots ?? []).map((spot) => spot.thumbnailUrl).filter(Boolean)
    const url = urls.find((candidate) => !used.has(candidate)) ?? urls[0] ?? null
    if (url) used.add(url)
    return url
  })
}
